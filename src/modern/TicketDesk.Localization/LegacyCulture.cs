        new("en-US", "English"),
        new("pt-BR", "Português do Brasil"),
        new("de-DE", "Deutsch (Deutschland)"),
    ];

    /// <summary>CultureHelper.GetImplementedCulture(name): valid → implemented as is, else same language, else the default.</summary>
    public static string GetImplementedCulture(string? name, string defaultCulture = DefaultCulture)
    {
        if (string.IsNullOrEmpty(name)) return defaultCulture;
        if (!ValidCultures.Contains(name)) return defaultCulture;
        foreach (var (key, _) in Cultures)
            if (key.Equals(name, StringComparison.InvariantCultureIgnoreCase)) return name;
        var neutral = name.Contains('-') ? name.Split('-')[0] : name;
        foreach (var (key, _) in Cultures)
            if (key.StartsWith(neutral, StringComparison.Ordinal)) return key;
        return defaultCulture;
    }
